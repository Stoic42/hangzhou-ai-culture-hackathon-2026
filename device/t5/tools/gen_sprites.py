from pathlib import Path
from PIL import Image

app = Path(__file__).resolve().parents[1]
assets = app.parents[1] / "docs/project/characters/圆屏状态像素包"
sets = {
    "last_one": "idle detail plead accept beckon refuse_1 refuse_2 success timeout",
    "do_now": "idle detail nudge step_1 step_2 reset stall success timeout",
    "decide_now": "idle detail offer_a offer_b lock_a lock_b reconsider success timeout",
}

def encode(image):
    if image.size != (64, 64):
        raise ValueError(image.size)
    # Native LVGL format: preserve alpha and bypass the indexed scanline decoder on T5.
    return image.convert("RGBA").tobytes("raw", "BGRA")

source = ['/* Generated by tools/gen_sprites.py. */', '#include "buddy_sprites.h"', '#include <string.h>']
rows = []
for creature, states in sets.items():
    for state in states.split():
        name = creature + "_" + state
        with Image.open(assets / creature / (state + ".png")) as image:
            pixels = encode(image)
        source.append(f"static const uint8_t LV_ATTRIBUTE_MEM_ALIGN {name}_data[] = {{")
        source.extend("    " + ",".join(map(str, pixels[i:i+32])) + "," for i in range(0, len(pixels), 32))
        source.append("};")
        source.append(f"static const lv_image_dsc_t {name} = {{")
        source.append("    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_ARGB8888, .w = 64, .h = 64, .stride = 256},")
        source.append(f"    .data_size = sizeof({name}_data), .data = {name}_data,")
        source.append("};")
        rows.append(f'    {{"bdy_preset_{creature}", "{state}", &{name}}},')
source += ['static const struct {const char *id; const char *frame; const lv_image_dsc_t *image;} images[] = {', *rows, '};',
           'const lv_image_dsc_t *buddy_sprite(const char *id, const char *frame)', '{',
           '    for (size_t i = 0; i < sizeof(images)/sizeof(images[0]); i++) {',
           '        if (!strcmp(id, images[i].id) && !strcmp(frame, images[i].frame)) return images[i].image;',
           '    }', '    return NULL;', '}']
(app / "src/generated/buddy_sprites.c").write_text("\n".join(source) + "\n", encoding="utf-8")
