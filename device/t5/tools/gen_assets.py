#!/usr/bin/env python3
"""Generate embedded assets for the T5 offline preset buddy firmware.

Inputs (relative to the repository root):
  shared/presets/*.json          rule pack v1 manifests (embedded as JSON text)
  shared/assets/feedback.pcm     16kHz mono 16bit feedback PCM
  device/t5/src/ui_text.h        UI strings (scanned for CJK glyphs)

Outputs (device/t5/src/generated/):
  builtin_presets.c              preset JSON blobs + builtin resource table
  feedback_pcm.c                 PCM bytes + size + sha256 hex
  buddy_*.c                      Noto Sans SC subset fonts and West Lake backgrounds

Usage (repository root):
  py -3.12 device/t5/tools/gen_assets.py [--sdk F:/t5open]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

DEVICE_DIR = Path(__file__).resolve().parent.parent
REPO_ROOT = DEVICE_DIR.parent.parent
SRC_DIR = DEVICE_DIR / "src"
OUT_DIR = SRC_DIR / "generated"
PRESET_ORDER = [
    "last-one.json",
    "do-now.json",
    "decide-now.json",
    "swipe-duel.json",
    "rhythm-tap.json",
    "shake-off.json",
]
def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--sdk", default=r"F:\t5open", help="TuyaOpen SDK path")
    parser.add_argument("--font", type=Path, default=Path("C:/Windows/Fonts/NotoSansSC-VF.ttf"))
    args = parser.parse_args()
    font_path = args.font
    if not font_path.is_file():
        print(f"error: Noto Sans SC variable TTF missing at {font_path}", file=sys.stderr)
        return 2

    OUT_DIR.mkdir(parents=True, exist_ok=True)

    # ---- presets -------------------------------------------------------------
    presets: list[tuple[str, str]] = []  # (symbol suffix, minified json text)
    for name in PRESET_ORDER:
        path = REPO_ROOT / "shared/presets" / name
        data = json.loads(path.read_text(encoding="utf-8"))
        text = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
        suffix = name[: -len(".json")].replace("-", "_")
        presets.append((suffix, text))

    # ---- feedback pcm --------------------------------------------------------
    pcm_path = REPO_ROOT / "shared/assets/feedback.pcm"
    pcm = pcm_path.read_bytes()
    pcm_sha = hashlib.sha256(pcm).hexdigest()

    # ---- builtin_presets.c ---------------------------------------------------
    lines = [
        "/* AUTO-GENERATED by tools/gen_assets.py. Do not edit by hand. */",
        '#include "builtin_assets.h"',
        "",
    ]
    for suffix, text in presets:
        lines.append(f"const char BUDDY_PRESET_{suffix.upper()}_JSON[] =")
        # split into chunks to keep C lines short
        step = 120
        parts = [text[i : i + step] for i in range(0, len(text), step)]
        for i, part in enumerate(parts):
            esc = part.replace("\\", "\\\\").replace('"', '\\"')
            lines.append('    "%s"' % esc + (";" if i == len(parts) - 1 else ""))
        lines.append("")
    lines.append("const buddy_preset_desc_t BUDDY_BUILTIN_PRESETS[] = {")
    for suffix, text in presets:
        lines.append(
            f'    {{BUDDY_PRESET_{suffix.upper()}_JSON, {len(text.encode("utf-8"))}}},'
        )
    lines.append("};")
    lines.append(f"const uint32_t BUDDY_BUILTIN_PRESET_COUNT = {len(presets)};")
    lines.append("")
    (OUT_DIR / "builtin_presets.c").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # ---- feedback_pcm.c ------------------------------------------------------
    pcm_lines = [
        "/* AUTO-GENERATED by tools/gen_assets.py. Do not edit by hand. */",
        '#include "builtin_assets.h"',
        "",
        f"const uint32_t BUDDY_FEEDBACK_PCM_SIZE = {len(pcm)};",
        f'const char BUDDY_FEEDBACK_SHA256[] = "{pcm_sha}";',
        "",
        "const uint8_t BUDDY_FEEDBACK_PCM[] = {",
    ]
    for i in range(0, len(pcm), 16):
        pcm_lines.append("    " + ", ".join(str(b) for b in pcm[i : i + 16]) + ",")
    pcm_lines.append("};")
    pcm_lines.append("")
    (OUT_DIR / "feedback_pcm.c").write_text("\n".join(pcm_lines) + "\n", encoding="ascii")

    from gen_ui_fonts import generate
    generate(SRC_DIR, font_path)
    from gen_lake import write_assets
    write_assets(OUT_DIR / "buddy_lakes.c")

    print(f"presets: {len(presets)} manifests embedded")
    print(f"pcm: {len(pcm)} bytes sha256={pcm_sha}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
