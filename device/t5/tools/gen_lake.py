"""Paint the West Lake backdrop on a 233px pixel grid and bake RGB565 strips."""
from pathlib import Path
from PIL import Image, ImageDraw

# Page ink, sky, far hills, near hills, water, moon, reflections, controls
PALETTES = (
    ('101a29', '34425c', '44536b', '29384e', '223247', 'd6bd8e', '536477', 'f0c783'),
    ('102621', '3b645d', '54766a', '2a5047', '20443e', 'c4d6a1', '628178', 'a9dec1'),
    ('231e30', '62516a', '746079', '493c55', '392e45', 'dbb1ab', '806578', 'e9bedb'),
)


def mix(a, b, t):
    return tuple(round(x + (y-x)*t) for x, y in zip(a, b))


def lake(theme):
    ink, sky, far, near, water, moon, glint, _ = [
        tuple(bytes.fromhex(s)) for s in PALETTES[theme]]
    im = Image.new('RGB', (233, 122), ink)
    d = ImageDraw.Draw(im)
    for y in range(85):
        d.line((0, y, 232, y), fill=mix(ink, sky, y/84))
    d.ellipse((161, 21, 179, 39), fill=moon)
    if theme == 0:
        d.ellipse((157, 18, 173, 34), fill=mix(ink, sky, .30))
    for x, y in [(42, 28), (66, 16), (184, 46), (150, 12), (30, 50)]:
        d.point((x, y), fill=glint)
    d.polygon([(0,60),(16,56),(26,59),(43,52),(57,54),(79,67),(100,61),
               (125,70),(153,55),(164,57),(181,45),(201,49),(221,61),
               (232,56),(232,88),(0,88)], fill=far)
    d.polygon([(0,66),(17,65),(40,74),(61,72),(83,81),(114,77),(135,82),
               (156,71),(180,68),(198,62),(215,63),(232,57),(232,87),(0,87)], fill=near)
    # A five-tier pagoda on the eastern bank.
    x = 199
    d.line((x, 38, x, 66), fill=ink)
    for i in range(5):
        y, w = 42+i*4, 2+i
        d.rectangle((x-w+1, y+1, x+w-1, y+4), fill=ink)
        d.polygon([(x-w-2,y+1),(x-1,y-1),(x+1,y-1),(x+w+2,y+1),
                   (x+w,y+2),(x-w,y+2)], fill=ink)
    for y in range(84, 122):
        d.line((0, y, 232, y), fill=mix(water, ink, (y-84)/37))
    # Three low bridge arches, open to the water below.
    d.polygon([(0,82),(15,79),(31,75),(45,74),(55,75),(71,81),(81,82),
               (81,85),(0,85)], fill=near)
    for x, w, y in [(19,7,81),(40,10,78),(62,7,81)]:
        d.ellipse((x-w,y,x+w,92), fill=water)
    for x, y, w in [(14,91,17),(34,96,11),(58,88,8),(166,87,14),
                    (184,90,23),(152,94,18),(177,99,10),(46,104,15),
                    (198,107,12),(8,111,7),(133,102,5)]:
        d.line((x,y,x+w,y), fill=mix(water, glint, .65))
    if theme == 0:
        # Stone lanterns in the lake, set well behind the gold animal.
        for x, y in [(36,91),(20,96),(53,87)]:
            d.polygon([(x-4,y),(x-2,y-2),(x-2,y-6),(x-4,y-8),(x,y-12),
                       (x+4,y-8),(x+2,y-6),(x+2,y-2),(x+4,y)],fill=ink)
            d.point((x,y-6), fill=moon)
    elif theme == 1:
        for x,y in [(25,45),(31,44),(167,50)]:
            d.line([(x-2,y-1),(x,y),(x+2,y-2)],fill=near)
        for x,y in [(9,91),(14,94),(19,89),(23,93),(213,98),(217,97),(224,95)]:
            d.line((x,y,x-2,y-6),fill=glint)
            d.line((x,y-1,x+2,y-5),fill=near)
    else:
        # Osmanthus boughs at the edge of the field of view.
        for path in [[(0,28),(14,31),(26,40),(46,43)],[(25,39),(36,33),(44,28)],
                     [(233,12),(218,19),(214,28),(198,35)]]:
            d.line(path, fill=near,width=2)
        for x,y in [(15,29),(25,38),(37,33),(42,29),(45,41),(201,33),(215,25),(220,18)]:
            d.polygon([(x,y),(x-5,y-3),(x-2,y-4),(x+2,y-1)], fill=glint)
            for dx,dy in [(-1,0),(1,0),(0,-1),(0,1)]:
                d.point((x+dx,y+2+dy), fill=moon)
    return im


def write_assets(out):
    lines = ['/* Generated by tools/gen_lake.py */', '#include "lvgl.h"']
    for i in range(3):
        im = lake(i).resize((466, 244), Image.Resampling.NEAREST)
        pixels = [(r >> 3) << 11 | (g >> 2) << 5 | b >> 3 for r,g,b in im.getdata()]
        lines.append(f'static const uint16_t lake_{i}_pixels[] = {{')
        for j in range(0, len(pixels), 20):
            lines.append('    ' + ','.join(hex(v) for v in pixels[j:j+20]) + ',')
        lines.append('};')
    lines.append('const lv_image_dsc_t buddy_lakes[] = {')
    for i in range(3):
        lines.append(f'    {{ .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565, .w = 466, .h = 244, .stride = 932 }}, .data_size = sizeof(lake_{i}_pixels), .data = (const uint8_t *)lake_{i}_pixels }},')
    lines.append('};')
    out.write_text('\n'.join(lines)+'\n', encoding='utf-8')


if __name__ == '__main__':
    write_assets(Path(__file__).resolve().parents[1] / 'src/generated/buddy_lakes.c')
