"""Bake Noto Sans SC into uncompressed 4bpp LVGL v9 subsets."""
from pathlib import Path
import re
from PIL import ImageFont


def bake(out, symbol, path, size, weight, chars):
    font = ImageFont.truetype(str(path), size)
    font.set_variation_by_axes([weight])
    codes = sorted(set(map(ord, chars)))
    tiles, descriptors = bytearray(), ['    {0},']
    for code in codes:
        ch = chr(code)
        mask, (left, top) = font.getmask2(ch, anchor='ls')
        w, h = mask.size
        descriptors.append(f'    {{.bitmap_index={len(tiles)}, .adv_w={round(font.getlength(ch)*16)}, .box_w={w}, .box_h={h}, .ofs_x={left}, .ofs_y={-top-h}}},')
        values = [v >> 4 for v in bytes(mask)] + [0]
        tiles.extend((values[i] << 4) | values[i+1] for i in range(0,w*h,2))
    lines = [f'/* Generated by tools/gen_ui_fonts.py, {size}px, ASCII -r 0x20-0x7E */',
             '#include "lvgl.h"', 'static const uint8_t bitmap[] = {']
    for i in range(0, len(tiles), 24):
        lines.append('    '+','.join(map(str,tiles[i:i+24]))+',')
    lines.extend(['};','static const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {', *descriptors, '};',
                  'static const uint16_t offsets[] = {', ','.join(str(c-codes[0]) for c in codes), '};',
                  'static const lv_font_fmt_txt_cmap_t cmap = {',
                  f'    .range_start={codes[0]}, .range_length={codes[-1]-codes[0]+1}, .glyph_id_start=1,',
                  f'    .unicode_list=offsets, .list_length={len(codes)}, .type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY',
                  '};','static const lv_font_fmt_txt_dsc_t data = {',
                  '    .glyph_bitmap=bitmap, .glyph_dsc=glyphs, .cmaps=&cmap, .cmap_num=1, .bpp=4,','};',
                  f'const lv_font_t {symbol} = {{', '    .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,',
                  '    .get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,',
                  f'    .line_height={size+5}, .base_line=5, .dsc=&data,','};'])
    out.write_text('\n'.join(lines)+'\n', encoding='utf-8')


def generate(src, font_path):
    gen = src / 'generated'
    manifest = (gen/'builtin_presets.c').read_text(encoding='utf-8')
    ui = (src/'ui_text.h').read_text(encoding='utf-8')
    strings = ''.join(re.findall(r'"([^"\n]*)"', ui))
    cjk = ''.join(sorted({c for c in strings+manifest if ord(c)>127}))
    (gen/'font_symbols.txt').write_text(cjk, encoding='utf-8')
    chars = ''.join(map(chr,range(32,127)))+cjk
    definitions = (
        ('buddy_font', 26, 400, chars),
        ('buddy_display', 38, 700, chars),
        ('buddy_caption', 22, 400, '本地妖怪 0123456789/'),
        ('buddy_heading', 28, 700, '当代妖怪收容所'),
        ('buddy_button', 26, 700, '返回生成搭子再玩一局点按开局'),
    )
    for symbol, size, weight, subset in definitions:
        bake(gen/(symbol+'.c'), symbol, font_path, size, weight, subset)


if __name__ == '__main__':
    import argparse
    p = argparse.ArgumentParser()
    p.add_argument('font', type=Path)
    generate(Path(__file__).resolve().parents[1]/'src', p.parse_args().font)
